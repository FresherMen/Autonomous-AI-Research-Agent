import os
import json
from dotenv import load_dotenv
from groq import Groq
from tools import TOOL_SCHEMAS_OPENAI, ToolExecutor

load_dotenv()

class ResearchAgent:

    MAX_ITERATIONS = 6
    MAX_HISTORY_MESSAGES = 20

    def __init__(self, executor: ToolExecutor = None):
        api_key = os.getenv("GROQ_API_KEY")
        if not api_key:
            raise EnvironmentError("GROQ_API_KEY is not configured in environment or .env file.")
        self.client   = Groq(api_key=api_key)
        self.executor = executor or ToolExecutor()
        self.history  = []
        self.last_tool_calls = []
        self.last_sources = []
        self.system = """You are an expert research assistant with access to
three tools: search_docs, search_web, and save_note.
Think step by step, call tools to gather information, then give a clear answer."""

    def run(self, user_goal: str) -> str:
        print(f"\n{'='*60}")
        print(f"Agent goal: {user_goal}")
        print('='*60)

        self.last_tool_calls = []
        self.last_sources = []

        self.history.append({"role": "user", "content": user_goal})

        # Bound history to prevent context window explosion
        if len(self.history) > self.MAX_HISTORY_MESSAGES:
            self.history = self.history[-self.MAX_HISTORY_MESSAGES:]

        for iteration in range(1, self.MAX_ITERATIONS + 1):
            print(f"\n── Iteration {iteration} ─────────────────")

            response = self.client.chat.completions.create(
                model      = "llama-3.3-70b-versatile",
                max_tokens = 2048,
                tools      = TOOL_SCHEMAS_OPENAI,
                messages   = [{"role": "system", "content": self.system}] + self.history
            )

            if not response.choices:
                return "Error: No response generated by the model."

            choice = response.choices[0]
            finish_reason = choice.finish_reason
            print(f"   Finish reason: {finish_reason}")

            if finish_reason == "tool_calls" and choice.message.tool_calls:
                msg = choice.message

                # Save assistant message with tool calls to history
                self.history.append({
                    "role":       "assistant",
                    "content":    msg.content or "",
                    "tool_calls": [
                        {
                            "id":       tc.id,
                            "type":     "function",
                            "function": {
                                "name":      tc.function.name,
                                "arguments": tc.function.arguments
                            }
                        }
                        for tc in msg.tool_calls
                    ]
                })

                # Execute each tool and collect results
                for tc in msg.tool_calls:
                    tool_name = tc.function.name
                    self.last_tool_calls.append(tool_name)

                    try:
                        raw_args = tc.function.arguments or "{}"
                        tool_args = json.loads(raw_args)
                        if not isinstance(tool_args, dict):
                            tool_args = {}
                    except json.JSONDecodeError as err:
                        tool_args = {}
                        result = f"Error: Malformed JSON arguments for tool '{tool_name}': {err}"
                    else:
                        result = self.executor.run(tool_name, tool_args)

                    if getattr(self.executor, "last_sources", None):
                        for src in self.executor.last_sources:
                            if src not in self.last_sources:
                                self.last_sources.append(src)

                    preview = result[:120] if result else ""
                    print(f"   Result preview: {preview}...")

                    self.history.append({
                        "role":         "tool",
                        "tool_call_id": tc.id,
                        "content":      result
                    })

            else:
                # end_turn or stop — return final answer
                final_answer = choice.message.content or ""
                self.history.append({"role": "assistant", "content": final_answer})
                print(f"\n✓ Agent finished in {iteration} iteration(s)")
                return final_answer

        return "Reached maximum steps. Please try a more specific question."

    def reset(self):
        self.history = []
        self.last_tool_calls = []
        self.last_sources = []
        print("Agent memory cleared.")